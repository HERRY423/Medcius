// Build-time only. No patient data or runtime dependency on pinyin-pro.
import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const require = createRequire(new URL('../plugins/medcius/runtimes/cn-phi-ner/package.json', import.meta.url));
const { polyphonic } = require('pinyin-pro');
const dir = new URL('../plugins/medcius/data/phi/', import.meta.url);
mkdirSync(dir, { recursive: true });
const map = {};
for (const [start,end] of [[0x3400,0x4dbf],[0x4e00,0x9fff]]) {
  for (let n=start;n<=end;n++) {
    const c = String.fromCodePoint(n);
    const sounds = [...new Set(polyphonic(c, { toneType: 'none', type: 'array' })[0])].filter(s => /^[a-zü]+$/.test(s)).sort();
    if (sounds.length) map[c] = sounds;
  }
}
writeFileSync(new URL('cn-pronunciations.v1.json', dir), JSON.stringify(map) + '\n');
writeFileSync(new URL('pinyin-pro-LICENSE.txt', dir), readFileSync(require.resolve('pinyin-pro/package.json').replace(/package.json$/, 'LICENSE')));
writeFileSync(new URL('README.md', dir), '# Chinese PHI phonetics\n\nGenerated by `scripts/build-cn-phi-phonetics.mjs` from pinyin-pro 3.29.5 (MIT).\nTone-free character readings, including heteronyms, in U+3400–4DBF and U+4E00–9FFF.\nUsed only to match the active session’s known names; not a general name recognizer.\nHomophone matches can over-redact; dialectal and out-of-table variants remain uncovered.\nNames and matching results are never added to this public table.\n');
console.log(JSON.stringify({ entries: Object.keys(map).length, output: fileURLToPath(dir) }));
