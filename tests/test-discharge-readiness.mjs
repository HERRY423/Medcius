import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import vm from "node:vm";
import { DischargeReadinessEngine as Engine } from "../plugins/medcius/lib/discharge-readiness-engine.mjs";
import { HospitalAgentAdapter, HOST_TYPES } from "../plugins/medcius/lib/hospital-agent-adapter.mjs";
import { ConsultPreparationEngine } from "../plugins/medcius/lib/consult-preparation-engine.mjs";
import { dischargeFixture, documentHash } from "./fixtures/discharge-documentation.mjs";
const { args, doc, snapshot, source, context, asOf } = dischargeFixture();
const check = patch => Engine.evaluateDischargeReadiness({ ...args, ...patch });
const full = check();
assert.equal(full.clinical_suitability.assessed, false);
assert.equal(full.clinical_suitability.is_suitable_for_discharge, null);
assert.equal(full.readiness_verdict.is_ready, null);
assert.equal(full.domains.results.status, "fields_present_in_supplied_records");
assert.equal(full.domains.medications.status, "fields_present_in_supplied_records");
assert.equal(full.domains.follow_up.status, "fields_present_in_supplied_records");
assert.equal(full.documentation_summary.coverage, "not_established");
assert.equal(full.domains.results.items[0].clinical_tasks_completed, false);
assert.equal(full.domains.follow_up.items[0].appointment_verified, false);
const bare = check({ dischargeMedications: [], medicationTransitions: [], followUpPlans: [], patientInstructions: [] });
assert.equal(bare.domains.follow_up.status, "unknown");
assert.ok(bare.findings.some(f => f.code === "FOLLOW_UP_SCOPE_UNKNOWN"), "negated note must not establish follow-up");
assert.equal(bare.readiness_verdict.is_ready, null);
const missing = { ...args.dischargeMedications[0], route: null, frequency: null };
const missingResult = check({ dischargeMedications: [missing] });
assert.equal(missingResult.domains.medications.discharge[0].record.route, null);
assert.ok(missingResult.findings.some(f => f.code === "DISCHARGE_MEDICATION_FIELDS_MISSING"));
assert.ok(missingResult.findings.some(f => f.code === "TRANSITION_REQUIRES_REVIEW"), "changed medication invalidates old content link");
const other = doc("other-med", { ...args.dischargeMedications[0], id: "other-med", drug_name: "合成药物乙" });
assert.ok(check({ dischargeMedications: [other] }).findings.some(f => f.code === "TRANSITION_DOCUMENTATION_MISSING"), "same route or drug class cannot imply equivalence");
const altered = { ...args.dischargeMedications[0], dosage: "10 mg" };
const linkedAlteration = { ...args.medicationTransitions[0], discharge_ref: { source_id: altered.id, content_sha256: documentHash(altered) } };
assert.ok(check({ dischargeMedications: [altered], medicationTransitions: [linkedAlteration] }).domains.medications.items[0].problems.includes("CONTINUE_FIELDS_DIFFER"));
const explicitChange = { ...linkedAlteration, action: "change", rationale_text: "来源提供者记录的合成调整说明" };
assert.equal(check({ dischargeMedications: [altered], medicationTransitions: [explicitChange] }).domains.medications.items[0].clinical_appropriateness, "not_assessed");
const stopped = { ...args.medicationTransitions[0], action: "stop", discharge_ref: null, rationale_text: "来源医师记录停止原因" };
assert.equal(check({ dischargeMedications: [], medicationTransitions: [stopped] }).domains.medications.items[0].documentation_status, "fields_present_in_supplied_records");
const unknownReport = { ...source.diagnosticReports[0], status: "unrecognized", impression: null, acknowledged: false };
const unknown = check({ snapshot: Engine.createSnapshot({ ...source, diagnosticReports: [unknownReport] }) });
assert.equal(unknown.domains.results.items[0].result_status, "unknown");
assert.equal(unknown.domains.results.items[0].record.impression, null);
assert.ok(!Engine.generateDischargeChecklistText({ readinessResult: unknown }).includes("正常回报"));
for (const status of ["cancelled", "entered-in-error", "preliminary"]) {
  const result = check({ snapshot: Engine.createSnapshot({ ...source, diagnosticReports: [{ ...source.diagnosticReports[0], status, cancelled_at: "2026-10-06T09:10:00Z" }] }) });
  assert.notEqual(result.domains.results.items[0].result_review_status, "closed");
  assert.equal(result.readiness_verdict.is_ready, null);
}
const corrected = { ...source.diagnosticReports[0], version_id: "r2", status: "corrected", updated_at: "2026-10-06T09:45:00Z", impression: "更正后的合成描述" };
const revised = check({ snapshot: Engine.createSnapshot({ ...source, diagnosticReports: [...source.diagnosticReports, corrected] }) });
assert.notEqual(revised.domains.results.items[0].review_status, "acknowledged");
assert.ok(revised.findings.some(f => f.code === "RESULT_TRACKING_DETAILS_MISSING"));
assert.ok(revised.domains.follow_up.items[0].missing_fields.includes("result_link_stale_or_missing"));
const incompletePlan = { ...args.followUpPlans[0], responsible_party: null, contact_route: null, appointment_reference: null };
const incomplete = check({ followUpPlans: [incompletePlan] });
assert.ok(incomplete.domains.follow_up.items[0].missing_fields.includes("appointment_reference"));
assert.ok(incomplete.domains.follow_up.items[0].missing_fields.includes("responsible_party"));
assert.ok(incomplete.domains.follow_up.items[0].missing_fields.includes("contact_route"));
const financial = [doc("cost", { kind: "patient_cost_estimate", category: "medication", status: "available", amount: 120, currency: "CNY", valid_until: "2026-10-13T00:00:00Z" }),
  doc("barrier", { kind: "affordability_screen", category: "medication", status: "barrier_reported" })];
const cost = check({ financialAccessRecords: financial });
assert.equal(cost.patient_affordability.assessment_status, "action_needed");
assert.equal(cost.clinical_suitability.is_suitable_for_discharge, null);
assert.equal(cost.patient_affordability.boundary.affects_clinical_discharge_verdict, false);
assert.ok(Engine.generateDischargeChecklistText({ readinessResult: cost }).includes("120 CNY"));
const expired = check({ financialAccessRecords: [{ ...financial[0], valid_until: "2026-10-01T00:00:00Z" }] });
assert.equal(expired.patient_affordability.verified_facts[0].status, "expired");
assert.ok(!Engine.generateDischargeChecklistText({ readinessResult: expired }).includes("120 CNY"));
const future = check({ followUpPlans: [{ ...args.followUpPlans[0], recorded_at: "2026-10-06T11:00:00Z" }] });
const withdrawn = check({ followUpPlans: [{ ...args.followUpPlans[0], status: "entered_in_error" }] });
assert.equal(withdrawn.domains.follow_up.items.length, 0);
assert.equal(future.domains.follow_up.items.length, 0);
assert.ok(future.excluded_records.documents.followUpPlans.some(r => r.reason === "future"));
const conflict = check({ followUpPlans: [{ ...args.followUpPlans[0], version_id: "v1" }, { ...args.followUpPlans[0], version_id: "v1", responsible_party: "other-team" }] });
assert.equal(conflict.domains.follow_up.items.length, 0, "same-version owner conflict must not select an arbitrary plan");
assert.ok(conflict.excluded_records.documents.followUpPlans.some(r => r.reason === "conflict"));
const reordered = check({ medicationTransitions: [...args.medicationTransitions, { ...args.medicationTransitions[0] }].reverse() });
assert.equal(reordered.packet_digest, full.packet_digest, "duplicate deliveries and input order do not change documentation state");
assert.throws(() => check({ followUpPlans: [{ ...args.followUpPlans[0], tenant_id: "wrong" }] }), /MISMATCH/);
assert.throws(() => check({ followUpPlans: [{ ...args.followUpPlans[0], subject: { reference: "Patient/wrong" } }] }), /MISMATCH/);
assert.throws(() => check({ patientInstructions: [doc("phi", { text: "电话 13800138000" })] }), /PHI/);
assert.throws(() => check({ snapshot: Engine.createSnapshot({ ...source, encounter: { ...source.encounter, class: "AMB" } }) }), /inpatient/);
assert.throws(() => check({ snapshot: Engine.createSnapshot({ ...source, encounter: { ...source.encounter, status: "finished" } }) }), /inpatient/);
const unbound = check({ dischargeMedications: [{ drug_name: "来源缺失药物" }] });
assert.equal(unbound.domains.medications.discharge.length, 0);
assert.ok(unbound.excluded_records.documents.dischargeMedications.some(r => r.reason === "SOURCE_REFERENCE_MISSING"));
assert.equal(ConsultPreparationEngine.prepareConsultDossier({ snapshot, consultRequest: { department: "肾内科", purpose: "整理检验" } }).snapshot_id, full.snapshot_id);
const adapted = HospitalAgentAdapter.executeDischargeReadinessWorkflow({ context: { ...context, as_of: asOf, doctor_id: "synthetic-doctor" },
  dataFeeds: { ...source, medications: source.medications, source_availability: source.sourceAvailability }, ...Object.fromEntries(Object.entries(args).filter(([key]) => key !== "snapshot")) });
assert.equal(adapted.readiness.readiness_verdict.is_ready, null);
assert.ok(adapted.provenance.envelope_sha256);
assert.throws(() => HospitalAgentAdapter.executeDischargeReadinessWorkflow({ host: HOST_TYPES.HIS_EMBED, context: { ...context, doctor_id: "d" }, dataFeeds: source }), /FROZEN|FORBIDDEN|not enabled/i);
const text = Engine.generateDischargeChecklistText({ readinessResult: full });
assert.ok(text.includes("资料完整性核对不能判定"));
assert.ok(!text.includes("电子核签"));
assert.ok(!text.includes("1~2 周"));
assert.equal(full.discharge_red_flags, undefined);
const ui = vm.createContext({ sessionStorage: { getItem: () => null } });
const template = readFileSync(new URL("../plugins/medcius/servers/api/src/ui/workstation.html", import.meta.url), "utf8");
vm.runInContext(template.match(/<script>([\s\S]*?)<\/script>/)[1], ui);
assert.match(ui.renderDischarge(full), /资料完整性核对不能判定/);
const malicious = structuredClone(full);
malicious.domains.results.items[0].title = '<img src=x onerror="alert(1)">';
malicious.domains.results.items[0].record['<script>'] = '<script>alert(1)</script>';
const rendered = ui.renderDischarge(malicious);
assert.ok(!rendered.includes('<img') && !rendered.includes('<script>'));
assert.ok(rendered.includes('&lt;img'));
console.log("Discharge documentation: independent result/medication/follow-up checks, explicit source links, lifecycle, PHI, expiry and no clinical discharge verdict passed.");
